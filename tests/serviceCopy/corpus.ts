/** Obfuscations of claim words inside an otherwise clean sentence. Every result must be dropped. */
export const CLAIM_WORDS = ['licensed', 'insured', 'guaranteed', 'certified', 'medical', 'treatment', 'dermatologist', 'warranty', 'experienced', 'therapy', 'promise', 'refund'];
const ZW = '​';
const HOMO: Record<string, string> = { a: 'а', e: 'е', o: 'о', c: 'с', i: 'і', p: 'р', s: 'ѕ', x: 'х', y: 'у' };
export const obfuscations: Record<string, (w: string) => string> = {
  zeroWidth: (w) => w.slice(0, 3) + ZW + w.slice(3),
  zeroWidthJoiner: (w) => w.split('').join('‍'),
  homoglyph: (w) => w.replace(/[aeocipsxy]/, (m) => HOMO[m]),
  fullwidth: (w) => w.replace(/[a-z]/g, (m) => String.fromCharCode(m.charCodeAt(0) + 0xfee0)),
  spaced: (w) => w.split('').join(' '),
  dotted: (w) => w.split('').join('.'),
  hyphenated: (w) => w.split('').join('-'),
  midHyphen: (w) => w.slice(0, 3) + '-' + w.slice(3),
  stretched: (w) => w.replace(/(.)/, '$1$1$1$1'),
  shouting: (w) => w.toUpperCase(),
  softHyphen: (w) => w.slice(0, 4) + '­' + w.slice(4),
  leet: (w) => w.replace(/[aeios]/g, (m) => ({ a: '4', e: '3', i: '1', o: '0', s: '5' } as Record<string, string>)[m]),
  combining: (w) => w.replace(/[aeiou]/, (m) => m + '́'),
};
export const obfuscatedHostile = (): string[] => CLAIM_WORDS.flatMap((w) => Object.values(obfuscations).map((f) => `Tell your barber about the ${f(w)} status.`));

